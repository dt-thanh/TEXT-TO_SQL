"""A research answer as a Markdown report: findings, the evidence behind them, SQL, caveats."""

from typing import Any

from src.agents.research.workflow import ResearchAnswer

UNIT_LABELS = {"fraction_per_year": "per year", "bps": "bps", "usd": "USD", "percent": "%"}


def format_value(value: float | str | None, unit: str) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, str):  # dates
        return value
    if unit in ("fraction", "fraction_per_year"):
        text = f"{value * 100:.2f}%"
        return f"{text} per year" if unit == "fraction_per_year" else text
    if unit == "usd":
        return f"{value:,.0f} USD"
    if unit == "count":
        return f"{value:.0f}"
    if unit == "ratio":
        return f"{value:.3f}"
    if unit == "sigma":
        return f"{value:.2f} sd"
    if unit == "price":  # USDT: 87,648.2 for BTC, 0.123457 for a small coin
        return f"{value:,.6g}" if abs(value) < 1e6 else f"{value:,.0f}"
    if unit == "percent":
        return f"{value:.2f}%"
    return f"{value:.4g} {UNIT_LABELS.get(unit, '')}".strip()


def evidence_section(item: dict[str, Any]) -> list[str]:
    params = ", ".join(f"{k}={v}" for k, v in item["params"].items())
    lines = [f"### {item['id']}: {item['metric_name']}", f"Parameters: {params}  "]
    lines.append(f"Sources: {', '.join(item['sources'])} · n = {item['n']}  ")
    if not item["usable"]:
        lines.append("**Not used: not enough observations.**  ")
    if item.get("rows"):
        lines += ["", *rows_table(item["rows"])]
    else:
        lines += ["", "| Result | Value |", "|---|---|"]
        for value in item["values"]:
            shown = format_value(value["value"], value["unit"])
            lines.append(f"| {value['description']} | {shown} |")
    lines += ["", "```sql", item["sql"], "```", ""]
    return lines


def rows_table(rows: list[dict[str, Any]]) -> list[str]:
    """A multi-row result as one Markdown table: key columns, then values, then n."""

    keys = list(rows[0]["key"])
    names = [value["column"].lower().replace("_", " ") for value in rows[0]["values"]]
    headers = [*[k.lower().replace("_", " ") for k in keys], *names]
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for row in rows:
        cells = [row["key"][k] for k in keys]
        cells += [format_value(v["value"], v["unit"]) for v in row["values"]]
        if not row["usable"]:  # the sample column is among the values; say why it is not used
            cells[-1] += " (not enough data)"
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def to_markdown(answer: ResearchAnswer) -> str:
    window = answer.analysis_window
    lines = [f"# {answer.question}", ""]
    lines.append(f"Status: **{answer.status}**  ")
    if window:
        lines.append(f"Period: {window[0]} to {window[1]} (UTC)  ")
    if answer.data_as_of:
        lines.append(f"Data up to: {answer.data_as_of.isoformat()}  ")
    sources = sorted({s for item in answer.evidence for s in item["sources"]})
    if sources:
        lines.append(f"Sources: {', '.join(sources)}")
    lines.append("")

    if answer.decline_reason and not answer.evidence:
        lines += ["## Not answered", answer.decline_reason, ""]
    if answer.findings:
        lines.append("## Findings")
        lines += [f"- {f['claim']} [{', '.join(f['evidence_ids'])}]" for f in answer.findings]
        lines.append("")
    if answer.evidence:
        lines.append("## Evidence")
        for item in answer.evidence:
            lines += evidence_section(item)
    unfinished = [task for task in answer.plan if task.get("status") not in (None, "done")]
    if unfinished:
        lines.append("## Not completed")
        for task in unfinished:
            lines.append(f"- {task['metric_id']}: {task['status']} ({task['reason']})")
        lines.append("")
    if answer.caveats:
        lines.append("## Caveats")
        lines += [f"- {caveat}" for caveat in answer.caveats]
        lines.append("")
    usage = answer.usage
    lines.append(
        f"_Generated by FinSight AI in {answer.seconds:.1f}s; LLM cost ${usage.cost_usd:.5f}. "
        "Every number comes from the SQL shown under Evidence._"
    )
    return "\n".join(lines) + "\n"
