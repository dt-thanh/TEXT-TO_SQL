"""Daily Brief: a research answer whose plan is built by code from a watchlist (spec v1.1, 5.7).

No new agent and no planner call. build_brief_plan turns the watchlist and the period into catalog
tasks; the research graph runs them exactly as for a question (resolver, templates, SQL guard,
read-only role, writer, grounding check). The tables and the list of risk signals are built here
from the evidence, so a brief is still useful when the writer fails, every finding is dropped, or
the LLM is switched off (`use_llm=False`: the "no LLM" mode of the product evaluation, and the
fallback when the daily cost cap is reached).

Signals describe past data by fixed rules (dbt/seeds/risk_signal_rules.csv); they are not
forecasts or advice, and the report says so in a line this code adds, not the writer.
"""

