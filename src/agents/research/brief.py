@dataclass(frozen=True)
class SignalRule:
    signal_id: str
    name: str
    unit: str
    comparison: str
    threshold: float
    window_days: int
    min_observations: int


def signal_rules(seed: Path = RULES_SEED) -> dict[str, SignalRule]:
    with seed.open(encoding="utf-8") as handle:
        return {
            row["signal_id"]: SignalRule(
                row["signal_id"],
                row["signal_name"],
                row["unit"],
                row["comparison"],
                float(row["threshold"]),
                int(row["window_days"]),
                int(row["min_observations"]),
            )
            for row in csv.DictReader(handle)
        }


@dataclass(frozen=True)
class BriefAnswer:
    research: ResearchAnswer
    watchlist_name: str | None
    symbols: tuple[str, ...]  # assets in the brief
    excluded: tuple[dict[str, str], ...]  # requested but not ready: symbol, reason
    window_days: int
    start: date | None
    end: date | None
    signals: tuple[dict[str, Any], ...]
    language: str
    used_llm: bool
    status: str
    markdown: str = ""
    extra: dict[str, Any] = field(default_factory=dict)


def brief_question(symbols: list[str], start: date, end: date, language: str) -> str:
    return TEXT[language]["question"].format(
        assets=", ".join(symbols), start=start.isoformat(), end=end.isoformat()
    )


def build_brief_plan(
    symbols: list[str], start: date, end: date, universe: tuple[dict[str, Any], ...]
) -> list[dict[str, Any]]:
    """The brief's tasks, in report order, at most MAX_TASKS. No LLM involved."""

    listed = ",".join(symbols)
    period = {"start_date": start.isoformat(), "end_date": end.isoformat()}
    tasks = [
        {"metric_id": "data_status", "params": {"symbols": listed}},
        {"metric_id": "watchlist_snapshot", "params": {"symbols": listed, **period}},
    ]
    if len(symbols) >= 2:
        tasks.append(
            {"metric_id": "return_correlation_matrix", "params": {"symbols": listed, **period}}
        )
    tasks.append({"metric_id": "risk_signals", "params": {"symbols": listed, **period}})
    tasks.append({"metric_id": "macro_rate_change", "params": dict(period)})
    inflation_start = min(start, end - timedelta(days=INFLATION_LOOKBACK_DAYS))
    tasks.append(
        {
            "metric_id": "inflation_change",
            "params": {"start_date": inflation_start.isoformat(), "end_date": end.isoformat()},
        }
    )
    # TVL only for chains mapped to an asset of the brief (dim_chain), never from a ticker.
    by_symbol = {row["SYMBOL"]: row.get("CHAIN_SLUG") for row in universe}
    chains = list(dict.fromkeys(c for s in symbols if (c := by_symbol.get(s))))[:MAX_CHAINS]
    for chain in chains:
        if len(tasks) < MAX_TASKS:
            tasks.append({"metric_id": "tvl_change", "params": {"chain": chain, **period}})
    return tasks[:MAX_TASKS]


def split_ready(
    symbols: list[str], universe: tuple[dict[str, Any], ...], today: date
) -> tuple[list[str], list[dict[str, str]]]:
    """Assets the brief can use (ready, recent data), and the others with the reason."""

    rows = {row["SYMBOL"]: row for row in universe}
    ready, excluded = [], []
    for symbol in symbols:
        row = rows.get(symbol)
        if row is None:
            excluded.append({"symbol": symbol, "reason": "loading"})
            continue
        status = row.get("STATUS")
        shown = "ready" if status == "ready" else status
        if shown == "ready":
            shown = display_status("ready", row.get("DATA_THROUGH"), today)
        if shown == "ready":
            ready.append(symbol)
        else:
            excluded.append({"symbol": symbol, "reason": shown})
    return ready, excluded


def code_planner(state: ResearchState) -> dict[str, Any]:
    """The graph's plan node for a brief: tasks from the watchlist, no model call."""

    brief = state["brief"]
    today = state["today"]
    ready, excluded = split_ready(brief["symbols"], state.get("universe", ()), today)
    if not state.get("universe"):  # universe not built yet: trust the core list
        ready, excluded = list(brief["symbols"]), []
    end = state.get("data_as_of") or today - timedelta(days=1)
    if brief.get("as_of"):  # a brief of a past day (evaluation, or looking back)
        end = min(end, brief["as_of"])
    start = end - timedelta(days=brief["window_days"] - 1)
    planned = {**brief, "ready": ready, "excluded": excluded, "start": start, "end": end}
    if not ready:
        reason = "no asset of the watchlist has recent data"
        return {"tasks": [], "decline_reason": reason, "brief": planned}
    return {
        "tasks": build_brief_plan(ready, start, end, state.get("universe", ())),
        "decline_reason": "",
        "question": brief_question(ready, start, end, brief["language"]),
        "brief": planned,
    }


def evidence_of(answer: ResearchAnswer, metric_id: str) -> list[dict[str, Any]]:
    return [item for item in answer.evidence if item["metric_id"] == metric_id and item["usable"]]


def collect_signals(answer: ResearchAnswer, rules: dict[str, SignalRule]) -> list[dict[str, Any]]:
    """Signals for the report: rows of the risk_signals metric, plus high_correlation, which
    depends on the watchlist and is checked here against its rule."""

    signals = []
    for item in evidence_of(answer, "risk_signals"):
        for row in item["rows"]:
            values = {v["column"]: v for v in row["values"]}
            rule = rules.get(row["key"]["SIGNAL_ID"])
            signals.append(
                {
                    "assets": row["key"]["SYMBOL"],
                    "signal_id": row["key"]["SIGNAL_ID"],
                    "name": rule.name if rule else row["key"]["SIGNAL_ID"],
                    "days_fired": values["DAYS_FIRED"]["value"],
                    "last_fired": values["LAST_FIRED"]["value"],
                    "value": values["LAST_VALUE"]["value"],
                    "threshold": values["THRESHOLD"]["value"],
                    "unit": values["LAST_VALUE"]["unit"],
                    "evidence_id": item["id"],
                }
            )
    rule = rules.get("high_correlation")
    for item in evidence_of(answer, "return_correlation_matrix"):
        for row in item["rows"]:
            value = row["values"][0]["value"]
            if rule and value is not None and (row["n"] or 0) >= rule.min_observations:
                if value >= rule.threshold:
                    signals.append(
                        {
                            "assets": f"{row['key']['SYMBOL_A']} / {row['key']['SYMBOL_B']}",
                            "signal_id": rule.signal_id,
                            "name": rule.name,
                            "days_fired": None,
                            "last_fired": item["params"].get("end_date"),
                            "value": value,
                            "threshold": rule.threshold,
                            "unit": rule.unit,
                            "evidence_id": item["id"],
                        }
                    )
    return signals


def brief_status(answer: ResearchAnswer, excluded: list[dict[str, str]], used_llm: bool) -> str:
    if answer.status in ("complete", "partial") and (excluded or not used_llm):
        return "partial"
    return answer.status


def generate_brief(
    symbols: list[str],
    window_days: int = 30,
    watchlist_name: str | None = None,
    language: str = "en",
    use_llm: bool = True,
    llm: LLMClient | None = None,
    warehouse: Any = None,
    layer: SemanticLayer | None = None,
    today: date | None = None,
    as_of: date | None = None,
) -> BriefAnswer:
    """Run one brief. Raises ValueError for a request outside the limits (the API's 422)."""

    symbols = list(dict.fromkeys(s.strip().upper() for s in symbols if s.strip()))
    if not 1 <= len(symbols) <= 10:
        raise ValueError("a brief needs 1 to 10 assets")
    if not MIN_WINDOW_DAYS <= window_days <= MAX_WINDOW_DAYS:
        raise ValueError(f"window_days must be {MIN_WINDOW_DAYS} to {MAX_WINDOW_DAYS}")
    language = language if language in TEXT else "en"

    llm = llm or (LLMClient() if use_llm else None)
    warehouse = warehouse or agent_warehouse()
    graph = build_research_graph(llm, warehouse, layer or load_semantic_layer(), code_planner)
    started = time.perf_counter()
    brief = {"symbols": symbols, "window_days": window_days, "language": language, "as_of": as_of}
    state = graph.invoke(
        {
            "question": f"{TEXT[language]['title']}: {', '.join(symbols)}",
            "today": today or datetime.now(UTC).date(),
            "started": started,
            "brief": brief,
            "max_seconds": MAX_SECONDS,
            "max_cost_usd": MAX_COST_USD,
            "use_writer": use_llm,
            "writer_optional": True,
        },
        config={"recursion_limit": RECURSION_LIMIT},
    )
    answer = to_research_answer(state, time.perf_counter() - started)
    brief = state["brief"]
    excluded = brief.get("excluded", [])
    result = BriefAnswer(
        research=answer,
        watchlist_name=watchlist_name,
        symbols=tuple(brief.get("ready", [])),
        excluded=tuple(excluded),
        window_days=window_days,
        start=brief.get("start"),
        end=brief.get("end"),
        signals=tuple(collect_signals(answer, signal_rules())),
        language=language,
        used_llm=use_llm,
        status=brief_status(answer, excluded, use_llm),
        extra={"writer_error": state.get("writer_error")},
    )
    markdown = brief_markdown(result)
    logger.info(
        "brief status=%s assets=%d excluded=%d signals=%d findings=%d cost_usd=%.5f seconds=%.1f",
        result.status,
        len(result.symbols),
        len(result.excluded),
        len(result.signals),
        len(answer.findings),
        answer.usage.cost_usd,
        answer.seconds,
    )
    return BriefAnswer(**{**result.__dict__, "markdown": markdown})


# --- Markdown --------------------------------------------------------------------------------


def overview_lines(brief: BriefAnswer, text: dict[str, str]) -> list[str]:
    lines = []
    for item in evidence_of(brief.research, "watchlist_snapshot"):
        rows = [r for r in item["rows"] if r["usable"]]
        returns = [
            (r["key"]["SYMBOL"], v["value"])
            for r in rows
            for v in r["values"]
            if v["column"] == "PERIOD_RETURN" and v["value"] is not None
        ]
        if len(returns) >= 2:
            best, worst = max(returns, key=lambda x: x[1]), min(returns, key=lambda x: x[1])
            lines.append(
                text["best"].format(
                    symbol=best[0],
                    value=format_value(best[1], "fraction"),
                    symbol2=worst[0],
                    value2=format_value(worst[1], "fraction"),
                )
            )
    firing = {s["assets"] for s in brief.signals}
    lines.append(text["active"].format(n=len(brief.signals), assets=len(firing)))
    for item in evidence_of(brief.research, "return_correlation_matrix"):
        values = [r["values"][0]["value"] for r in item["rows"] if r["usable"]]
        values = [v for v in values if v is not None]
        if values:
            low, high = f"{min(values):.2f}", f"{max(values):.2f}"
            lines.append(text["corr"].format(range=low if low == high else f"{low} – {high}"))
    return [f"- {line}" for line in lines]


def signals_table(brief: BriefAnswer) -> list[str]:
    lines = [
        "| Asset | Signal | Last fired | Value | Threshold | Days fired |",
        "|---|---|---|---|---|---|",
    ]
    for s in brief.signals:
        days = "—" if s["days_fired"] is None else f"{s['days_fired']:.0f}"
        value = format_value(s["value"], s["unit"])
        threshold = format_value(s["threshold"], s["unit"])
        lines.append(
            f"| {s['assets']} | {s['name']} | {s['last_fired']} | {value} | {threshold} | {days} |"
        )
    return lines


def context_lines(brief: BriefAnswer) -> list[str]:
    lines = []
    for metric_id in ("macro_rate_change", "inflation_change", "tvl_change"):
        for item in evidence_of(brief.research, metric_id):
            label = item["metric_name"]
            if "chain" in item["params"]:
                label += f" ({item['params']['chain']})"
            shown = [
                f"{v['description'].rstrip('.')}: {format_value(v['value'], v['unit'])}"
                for v in item["values"][:3]
                if v["value"] is not None
            ]
            lines.append(f"- **{label}** [{item['id']}]: " + "; ".join(shown))
    return lines


def brief_markdown(brief: BriefAnswer) -> str:
    text = TEXT[brief.language]
    answer = brief.research
    name = brief.watchlist_name or ", ".join(brief.symbols)
    lines = [f"# {text['title']}: {name}", ""]
    if brief.start and brief.end:
        lines.append(f"Period: {brief.start.isoformat()} → {brief.end.isoformat()} (UTC)  ")
    lines.append(f"Status: **{brief.status}**  ")
    if answer.data_as_of:
        lines.append(f"Data up to: {answer.data_as_of.isoformat()}")
    lines.append("")

    lines += [f"## {text['overview']}", *overview_lines(brief, text), ""]
    for item in evidence_of(answer, "watchlist_snapshot"):
        lines += [f"## {text['performance']} [{item['id']}]", *rows_table(item["rows"]), ""]
    lines.append(f"## {text['signals']}")
    lines += signals_table(brief) if brief.signals else [text["no_signals"]]
    lines += ["", f"_{text['disclaimer']}_", ""]
    context = context_lines(brief)
    if context:
        lines += [f"## {text['context']}", *context, ""]

    lines.append(f"## {text['findings']}")
    if answer.findings:
        lines += [f"- {f['claim']} [{', '.join(f['evidence_ids'])}]" for f in answer.findings]
    else:
        reason = (
            text["writer_off"]
            if not brief.used_llm
            else text["writer_failed"]
            if brief.extra.get("writer_error")
            else text["writer_none"]
        )
        lines.append(text["no_findings"].format(reason=reason))
    lines.append("")

    lines.append(f"## {text['data_status']}")
    for item in evidence_of(answer, "data_status"):
        lines += rows_table(item["rows"])
    lines += [f"- {text['excluded'].format(**e)}" for e in brief.excluded]
    unfinished = [t for t in answer.plan if t.get("status") not in (None, "done")]
    lines += [f"- {t['metric_id']}: {t['status']} ({t['reason']})" for t in unfinished]
    lines.append("")

    if answer.caveats:
        lines += [f"## {text['caveats']}", *[f"- {c}" for c in answer.caveats], ""]
    lines.append(f"## {text['evidence']}")
    for item in answer.evidence:
        lines += evidence_section(item)
    lines.append(
        "_"
        + text["footer"].format(seconds=answer.seconds, cost=answer.usage.cost_usd)
        + " "
        + text["disclaimer"]
        + "_"
    )
    return "\n".join(lines) + "\n"


def brief_to_dict(brief: BriefAnswer) -> dict[str, Any]:
    """The brief as JSON-ready data: for the API response and CONTROL.DAILY_BRIEF."""

    answer = brief.research
    return {
        "watchlist_name": brief.watchlist_name,
        "status": brief.status,
        "symbols": list(brief.symbols),
        "excluded": list(brief.excluded),
        "window_days": brief.window_days,
        "start": brief.start.isoformat() if brief.start else None,
        "end": brief.end.isoformat() if brief.end else None,
        "data_as_of": answer.data_as_of.isoformat() if answer.data_as_of else None,
        "signals": list(brief.signals),
        "findings": answer.findings,
        "caveats": answer.caveats,
        "evidence": answer.evidence,
        "plan": answer.plan,
        "used_llm": brief.used_llm,
        "usage": {
            "input_tokens": answer.usage.input_tokens,
            "output_tokens": answer.usage.output_tokens,
            "cost_usd": answer.usage.cost_usd,
        },
        "seconds": answer.seconds,
        "timings": answer.timings,
        "markdown": brief.markdown,
    }
